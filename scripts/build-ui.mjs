import {build} from 'esbuild';
import {readFile, writeFile} from 'node:fs/promises';
const result = await build({entryPoints:['ui/components.jsx'], bundle:true, minify:true, write:false, format:'iife', target:'es2020', define:{'process.env.NODE_ENV':'"production"'}, legalComments:'inline'});
const js = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const css = await readFile('ui/mobile.css','utf8');
const block = `<!-- HCX UI START: generated by npm run build -->\n<style id="hcx-components">${css}</style>\n<script>${js}</script>\n<!-- HCX UI END -->`;
let html = await readFile('index.html','utf8');
html = html.includes('<!-- HCX UI START:') ? html.replace(/<!-- HCX UI START:[\s\S]*?<!-- HCX UI END -->/, () => block) : html.replace('</head>', () => block+'\n</head>');
await writeFile('index.html', html);
